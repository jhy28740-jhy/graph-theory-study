import io
p = '进展报告_前三大特征值之和的精确上界.tex'
s = io.open(p, encoding='utf-8-sig').read()
old = r"""\mathcal{Z}:=\{(0,4,0),(0,2,2),(0,0,4)\},
\]
分别称为 \textbf{$w$-块}与 \textbf{$a{=}0$ 块}；其权重之和为 $1+6+6+1+6+1=21$，
丢掉的九个模式（$(3,1,0),(3,0,1),(2,1,1),(1,3,0),(1,0,3),(1,2,1),(1,1,2),(0,3,1),(0,1,3)$）
共 $60$ 份权重，全部非负，可以直接扔掉。"""
new = r"""\mathcal{Z}:=\{(0,4,0),(0,2,2),(0,0,4)\},
\]
分别称为 \textbf{$w$-块}与 \textbf{$a{=}0$ 块}；其权重之和为 $1+6+6+1+6+1=21$。
丢掉的九个模式
\[
(3,1,0),(3,0,1),(2,1,1),(1,3,0),(1,0,3),(1,2,1),(1,1,2),(0,3,1),(0,1,3)
\]
共 $60$ 份权重，全部非负，可以直接扔掉。"""
assert old in s
s = s.replace(old, new, 1)
io.open(p, 'w', encoding='utf-8').write(s)
print('fixed')
